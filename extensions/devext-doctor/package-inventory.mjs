/**
 * package-inventory.mjs — the one reader of the installed extension surface, for both doctors.
 *
 * The package ships two diagnostics that answer the same question: `npx @kroffske/locus-pi doctor`
 * and `/devext doctor`. They used to answer it from different sources — the CLI walked
 * `package.json#pi.extensions` and checked files on disk, while the command read a hand-maintained
 * table of thirty-one historical rows that had drifted (it never listed `status-line`, and it still
 * named demos deleted long ago). Two doctors that disagree about what is installed are worse than
 * one, so both now read this module and nothing else.
 *
 * What it reports is deliberately narrow: the entrypoints this installation declares, whether each
 * one and its manifest are actually on disk, and the `risk` / `ownershipStatus` those manifests
 * declare. Migration history, disabled experiments and deleted fixtures are not evidence about an
 * installed package; they belong to Git history and the tracker.
 *
 * JavaScript, not TypeScript, because `bin/locus-pi` runs under plain `node` with no loader and has
 * to import it directly. JSDoc types are checked by `npm run typecheck` (`allowJs`/`checkJs`), so
 * `extensions/devext-doctor/index.ts` consumes it as a typed module.
 *
 * Two boundaries this module does not cross:
 *
 *   It does not validate manifests. `scripts/check-extension-manifests.ts` owns the manifest
 *   contract against `extension-manifest.schema.json` and runs in `npm run check`; that gate is a
 *   repository file and is not published. Here a manifest is only read, and anything unreadable
 *   becomes a stated problem rather than a thrown stack trace — a doctor that crashes on the fault
 *   it exists to report is not a doctor.
 *
 *   It does not enumerate commands, tools or workflows. The public catalog of those is generated by
 *   `npm run build:catalogs` into `dist/public-catalogs.json` and the documentation; duplicating it
 *   here would create the second source this module exists to remove.
 */
import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * The only entrypoint spelling `package.json#pi.extensions` accepts; group 1 is the extension
 * directory. `scripts/extension-manifest-sources.ts` states the same rule for the repository-side
 * gates, which cannot be imported from a published file. `tests/contracts/doctor/package-inventory.test.ts`
 * fails when the two spellings drift apart.
 */
export const ENTRYPOINT_PATTERN = /^\.\/extensions\/([^/]+)\/index\.ts$/u;

/**
 * Why one row is not usable evidence. `ok` is the only state that proves the entrypoint and its
 * manifest are both present and readable in this installation.
 *
 * @typedef {"ok" | "invalid-entrypoint" | "missing-entrypoint" | "missing-manifest" | "unreadable-manifest"} InventoryRowState
 */

/**
 * One declared entrypoint, resolved as far as this installation allows.
 *
 * `id`, `risk` and `ownership` are read from the manifest and fall back to `"unknown"` when it could
 * not be read, so a degraded row still renders instead of disappearing from the count.
 *
 * @typedef {object} InventoryRow
 * @property {InventoryRowState} state
 * @property {string} entrypoint  as written in `package.json#pi.extensions`
 * @property {string} directory   extension directory name, or the raw entrypoint when unparseable
 * @property {string} id          manifest `id`
 * @property {string} manifestPath package-relative path to the manifest
 * @property {string} risk        manifest `risk`
 * @property {string} ownership   manifest `ownershipStatus`
 * @property {string} [problem]   one sentence naming what is wrong, present unless `state` is `"ok"`
 */

/**
 * The installed surface of one package root.
 *
 * `problems` is the fail-closed signal both doctors act on: empty means every declared entrypoint
 * and manifest was found and read.
 *
 * @typedef {object} PackageInventory
 * @property {string} packageRoot
 * @property {string} name
 * @property {string} version
 * @property {InventoryRow[]} rows
 * @property {string[]} problems
 */

/** The installed package root, derived from this file's own location: `<root>/extensions/devext-doctor/`. */
export function defaultPackageRoot() {
  return path.dirname(path.dirname(path.dirname(fileURLToPath(import.meta.url))));
}

/**
 * Read the declared entrypoints of an installed package and their manifests, in declaration order.
 *
 * Never throws for a fault in the package it inspects: an unreadable `package.json`, a malformed
 * `pi.extensions`, a missing file and an unparseable manifest all come back as `problems`.
 *
 * @param {string} [packageRoot] defaults to the root this file was loaded from
 * @returns {PackageInventory}
 */
export function readPackageInventory(packageRoot = defaultPackageRoot()) {
  /** @type {string[]} */
  const problems = [];
  const packageJson = readJsonObject(path.join(packageRoot, "package.json"));
  if (packageJson.problem !== undefined) {
    problems.push(`package.json: ${packageJson.problem}`);
    return { packageRoot, name: "unknown", version: "unknown", rows: [], problems };
  }

  const value = packageJson.value;
  const name = typeof value.name === "string" ? value.name : "unknown";
  const version = typeof value.version === "string" ? value.version : "unknown";
  const pi = typeof value.pi === "object" && value.pi !== null ? value.pi : {};
  const entrypoints = /** @type {Record<string, unknown>} */ (pi).extensions;
  if (!Array.isArray(entrypoints)) {
    problems.push("package.json: pi.extensions must be an array of extension entrypoints");
    return { packageRoot, name, version, rows: [], problems };
  }

  const rows = entrypoints.map((entrypoint) => readRow(packageRoot, entrypoint));
  for (const row of rows) if (row.problem !== undefined) problems.push(row.problem);
  return { packageRoot, name, version, rows, problems };
}

/**
 * Resolve one declared entrypoint into a row. Stops at the first fault, because a missing file
 * makes every later question about that entrypoint unanswerable rather than merely unanswered.
 *
 * @param {string} packageRoot
 * @param {unknown} entrypoint
 * @returns {InventoryRow}
 */
function readRow(packageRoot, entrypoint) {
  const declared = typeof entrypoint === "string" ? entrypoint : String(entrypoint);
  const directory = typeof entrypoint === "string" ? (ENTRYPOINT_PATTERN.exec(entrypoint)?.[1] ?? "") : "";
  if (directory === "") {
    return degraded(
      "invalid-entrypoint",
      declared,
      declared,
      "",
      `${declared}: not an ./extensions/<id>/index.ts entrypoint`,
    );
  }

  const manifestPath = `extensions/${directory}/manifest.json`;
  if (!existsSync(path.join(packageRoot, declared.replace(/^\.\//u, "")))) {
    return degraded(
      "missing-entrypoint",
      declared,
      directory,
      manifestPath,
      `${declared}: declared entrypoint is missing`,
    );
  }
  if (!existsSync(path.join(packageRoot, manifestPath))) {
    return degraded("missing-manifest", declared, directory, manifestPath, `${manifestPath}: manifest is missing`);
  }

  const manifest = readJsonObject(path.join(packageRoot, manifestPath));
  if (manifest.problem !== undefined) {
    return degraded("unreadable-manifest", declared, directory, manifestPath, `${manifestPath}: ${manifest.problem}`);
  }

  return {
    state: "ok",
    entrypoint: declared,
    directory,
    id: stringField(manifest.value.id, directory),
    manifestPath,
    risk: stringField(manifest.value.risk, "unknown"),
    ownership: stringField(manifest.value.ownershipStatus, "unknown"),
  };
}

/**
 * @param {InventoryRowState} state
 * @param {string} entrypoint
 * @param {string} directory
 * @param {string} manifestPath
 * @param {string} problem
 * @returns {InventoryRow}
 */
function degraded(state, entrypoint, directory, manifestPath, problem) {
  return { state, entrypoint, directory, id: directory, manifestPath, risk: "unknown", ownership: "unknown", problem };
}

/**
 * @param {unknown} value
 * @param {string} fallback
 * @returns {string}
 */
function stringField(value, fallback) {
  return typeof value === "string" && value !== "" ? value : fallback;
}

/**
 * Read a JSON object, reporting rather than throwing. A JSON array or scalar is a fault too: every
 * file this module reads is specified as an object.
 *
 * @param {string} file
 * @returns {{ value: Record<string, unknown>, problem?: undefined } | { value?: undefined, problem: string }}
 */
function readJsonObject(file) {
  let text;
  try {
    text = readFileSync(file, "utf8");
  } catch (error) {
    return { problem: `unreadable (${error instanceof Error ? error.message : String(error)})` };
  }
  try {
    const parsed = JSON.parse(text);
    if (typeof parsed !== "object" || parsed === null || Array.isArray(parsed))
      return { problem: "is not a JSON object" };
    return { value: /** @type {Record<string, unknown>} */ (parsed) };
  } catch (error) {
    return { problem: `is not valid JSON (${error instanceof Error ? error.message : String(error)})` };
  }
}

/**
 * Count rows by one declared field, as sorted `label=count` pairs. Both doctors summarize risk and
 * ownership this way, and neither should re-derive the ordering.
 *
 * @param {InventoryRow[]} rows
 * @param {"risk" | "ownership"} field
 * @returns {string[]}
 */
export function countBy(rows, field) {
  /** @type {Map<string, number>} */
  const counts = new Map();
  for (const row of rows) counts.set(row[field], (counts.get(row[field]) ?? 0) + 1);
  return [...counts.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([label, count]) => `${label}=${count}`);
}
